-- Runs the codec against shared/test-vectors.json.
--   lua addon/tests/run.lua       (stock Lua 5.1 or LuaJIT; WoW runs Lua 5.1)
-- Exits non-zero on failure.

local here = (arg and arg[0] or ""):match("^(.*)[/\\]") or "."
local root = here .. "/../.."

local function loadLua(path)
  local f = assert(loadfile(path))
  return f()
end

local JSON = loadLua(here .. "/json.lua")
local Codec = loadLua(root .. "/addon/BountyLine/Codec.lua")
Codec.LibDeflate = loadLua(root .. "/addon/BountyLine/Libs/LibDeflate/LibDeflate.lua")

local fh = assert(io.open(root .. "/shared/test-vectors.json", "rb"))
local vectors = JSON.decode(fh:read("*a"))
fh:close()

local passed, failed = 0, 0

local function check(name, ok, detail)
  if ok then
    passed = passed + 1
  else
    failed = failed + 1
    print("FAIL  " .. name .. (detail and ("\n      " .. detail) or ""))
  end
end

local function show(x) return x == nil and "nil" or tostring(x) end

local function deepEqual(a, b, path)
  path = path or "fields"
  if type(a) ~= type(b) then return false, ("%s: %s vs %s"):format(path, show(a), show(b)) end
  if type(a) ~= "table" then
    if a == b then return true end
    return false, ("%s: %s vs %s"):format(path, show(a), show(b))
  end
  for k, v in pairs(a) do
    local ok, why = deepEqual(v, b[k], path .. "." .. tostring(k))
    if not ok then return false, why end
  end
  for k in pairs(b) do
    if a[k] == nil then return false, path .. "." .. tostring(k) .. " missing" end
  end
  return true
end

local function hexToBytes(hex)
  return (hex:gsub("..", function(h) return string.char(tonumber(h, 16)) end))
end

local function bytesToHex(s)
  return (s:gsub(".", function(c) return ("%02X"):format(c:byte()) end))
end

-- JSON null stands for a missing field.
local function stripNulls(t)
  if type(t) ~= "table" then return t end
  for k, v in pairs(t) do
    if v == JSON.null then t[k] = nil else stripNulls(v) end
  end
  return t
end

-- primitives
for _, v in ipairs(vectors.crc16) do
  local got = ("%04X"):format(Codec._test.crc16(v.input))
  check("crc16 " .. v.input, got == v.crc, "got " .. got)
end
for _, v in ipairs(vectors.adler32) do
  local got = ("%08X"):format(Codec._test.adler32(v.input))
  check("adler32 " .. v.adler, got == v.adler, "got " .. got)
end
for _, v in ipairs(vectors.base32) do
  local enc = Codec._test.base32Encode(hexToBytes(v.hex))
  check("base32 encode " .. v.hex, enc == v.b32, "got " .. enc)
  local dec = Codec._test.base32Decode(v.b32)
  check("base32 decode " .. v.b32, dec and bytesToHex(dec) == v.hex, "got " .. show(dec and bytesToHex(dec)))
end

-- codes: encode (B/K/L; packs are only generated by the Worker), decode, canonical round trip
for _, v in ipairs(vectors.codes) do
  if v.type ~= "P" then
    local code, err, msg = Codec.Encode(v.type, v.fields)
    check(v.name .. ": encodes", code == v.code, "got " .. show(code) .. " " .. show(err) .. " " .. show(msg))
  end
  local res, derr, dmsg = Codec.Decode(v.code)
  if not res then
    check(v.name .. ": decodes", false, show(derr) .. ": " .. show(dmsg))
  else
    check(v.name .. ": decoded type", res.type == v.type, "got " .. show(res.type))
    check(v.name .. ": decoded code", res.code == v.code, "got " .. show(res.code))
    local same, why = deepEqual(res.fields, v.decoded or v.fields)
    check(v.name .. ": decoded fields", same, why)
    if v.type ~= "P" then
      check(v.name .. ": re-encodes", Codec.Encode(res.type, res.fields) == v.code)
    end
  end
end

for _, v in ipairs(vectors.forwardCompat) do
  local res, err, msg = Codec.Decode(v.code)
  local same, why = false, show(err) .. ": " .. show(msg)
  if res then same, why = deepEqual(res.fields, v.fields) end
  check("forward compat " .. v.name, same, why)
end

for _, v in ipairs(vectors.normalization) do
  local res, err = Codec.Decode(v.input)
  check("normalization " .. v.input:gsub("%s", " "), res and res.code == v.normalized, "got " .. show(res and res.code or err))
end

for _, v in ipairs(vectors.invalid) do
  local res, err, msg = Codec.Decode(v.code)
  check("invalid " .. v.name .. " -> " .. v.error, res == nil and err == v.error,
    "got " .. (res and "ok" or show(err) .. " (" .. show(msg) .. ")"))
end

for _, v in ipairs(vectors.packs.cases) do
  local res, err, msg, received, total = Codec.DecodePack(v.input)
  if v.fields then
    local same, why = false, show(err) .. ": " .. show(msg)
    if res then same, why = deepEqual(res.fields, v.fields) end
    check("pack " .. v.name, same, why)
  else
    check("pack " .. v.name .. " -> " .. v.error, res == nil and err == v.error,
      "got " .. (res and "ok" or show(err) .. " (" .. show(msg) .. ")"))
    if v.received then
      local same, why = deepEqual({ received = received, total = total }, { received = v.received, total = v.total })
      check("pack " .. v.name .. ": received parts", same, why)
    end
  end
end

for _, v in ipairs(vectors.encodeErrors) do
  local code, err = Codec.Encode(v.type, stripNulls(v.fields))
  check("encode error " .. v.name, code == nil and err == "INVALID", "got " .. show(code or err))
end

-- every single-character substitution in a K payload is caught
do
  local code
  for _, v in ipairs(vectors.codes) do
    if v.type == "K" then code = v.code; break end
  end
  local start = code:find("-", 5, true) + 1
  local stop = #code - 5
  local alphabet = Codec.ALPHABET
  local caught = true
  for i = start, stop do
    for j = 1, #alphabet do
      local ch = alphabet:sub(j, j)
      if ch ~= code:sub(i, i) and Codec.Decode(code:sub(1, i - 1) .. ch .. code:sub(i + 1)) then caught = false end
    end
  end
  check("every single-character substitution is caught", caught)
end

print(("%d passed, %d failed"):format(passed, failed))
os.exit(failed == 0 and 0 or 1)
