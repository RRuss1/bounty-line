/**
 * Renders worker/wrangler.jsonc (gitignored) from wrangler.template.jsonc.
 *
 *   npm run render-config
 *
 * Values come from the process environment (GitHub Actions Variables in CI),
 * falling back to worker/.deploy.env for local deploys. Nothing rendered is
 * ever committed (Compendium 01 Section 3).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const dir = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));

/** Parses KEY=VALUE lines (# comments, optional quotes). */
export function parseEnvFile(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    out[m[1]!] = m[2]!.replace(/^(["'])(.*)\1$/, "$2");
  }
  return out;
}

const PLACEHOLDER = /\$\{([A-Z0-9_]+)(?::-([^}]*))?\}/g;

/** Substitutes ${NAME} and ${NAME:-default}. Throws listing every missing required value. */
export function renderTemplate(template: string, values: Record<string, string | undefined>): string {
  const missing = new Set<string>();
  const out = template.replace(PLACEHOLDER, (_, name: string, fallback: string | undefined) => {
    const v = values[name];
    if (v !== undefined && v !== "") return jsonEscape(v);
    if (fallback !== undefined) return jsonEscape(fallback);
    missing.add(name);
    return "";
  });
  if (missing.size) throw new Error(`Missing deployment values: ${[...missing].join(", ")}`);
  return out;
}

// Values land inside JSON strings; escape so a stray quote can't break or inject config.
const jsonEscape = (v: string) => JSON.stringify(v).slice(1, -1);

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const envFile = dir(".deploy.env");
  const fileValues = existsSync(envFile) ? parseEnvFile(readFileSync(envFile, "utf8")) : {};
  const values = { ...fileValues, ...process.env };
  const rendered = renderTemplate(readFileSync(dir("wrangler.template.jsonc"), "utf8"), values);
  writeFileSync(dir("wrangler.jsonc"), `// GENERATED by scripts/render-config.ts. Do not edit or commit.\n${rendered}`);
  console.log(`Rendered wrangler.jsonc for Worker "${values.WORKER_NAME}"`);
}
